/**
 * Builds src/lib/local-images.ts from the QC manifests in
 * ~/workspace/duo-tots-image-rebuild/manifest-parts/*.json.
 *
 * Only entries with qc "pass" / "pass-regenerated" whose file actually
 * exists under public/ are included — everything else stays on the
 * Wikipedia/API fallback path. Safe to re-run as more waves land.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const REPO = join(process.cwd());
const PARTS_DIR = join(REPO, "..", "duo-tots-image-rebuild", "manifest-parts");
const OUT = join(REPO, "src", "lib", "local-images.ts");

const PASS_QC = new Set(["pass", "pass-regenerated"]);

/** Entries a generation child verified verbally but never wrote a manifest for. */
const MANUAL = [
  // kid_general part A: Eraser + Backpack QC-passed (child report, 2026-11-06)
  { category: "kid_general", slug: "eraser" },
  { category: "kid_general", slug: "backpack" },
];

const map = new Map();

function addFromPath(rawPath) {
  const normalized = rawPath.replace(/^public/, "").replace(/^\/?/, "/");
  const m = normalized.match(/^\/images\/([^/]+)\/([^/]+)\.webp$/);
  if (!m) return false;
  const [, category, slug] = m;
  if (!existsSync(join(REPO, "public", normalized))) return false;
  map.set(`${category}:${slug}`, normalized);
  return true;
}

let files = [];
try {
  files = readdirSync(PARTS_DIR).filter((f) => f.endsWith(".json"));
} catch {
  console.error(`manifest-parts dir not found: ${PARTS_DIR}`);
}
for (const file of files) {
  const data = JSON.parse(readFileSync(join(PARTS_DIR, file), "utf8"));
  for (const [word, entry] of Object.entries(data)) {
    if (word.startsWith("_")) continue;
    if (!entry || typeof entry !== "object" || !PASS_QC.has(entry.qc)) continue;
    if (!entry.path || !addFromPath(entry.path)) {
      console.warn(`skip (missing on disk): ${file} :: ${word} -> ${entry.path}`);
    }
  }
}
for (const { category, slug } of MANUAL) {
  const p = `/images/${category}/${slug}.webp`;
  if (existsSync(join(REPO, "public", p))) map.set(`${category}:${slug}`, p);
}

const sorted = [...map.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines = sorted.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const out = `/**
 * Local rebuilt images — AUTO-GENERATED by scripts/build-local-images.mjs.
 * Do not edit by hand; re-run the script after new QC manifests land.
 *
 * Key: "\${categoryId}:\${assetKey ?? word slug}". Value: public web path.
 * Only images that passed visual QC against the reference standard are
 * listed; every other word falls back to the /api/media pipeline.
 */
export const LOCAL_IMAGES: Record<string, string> = {
${lines.join("\n")}
};

export function getLocalImage(categoryId: string, key: string): string | undefined {
  return LOCAL_IMAGES[\`\${categoryId}:\${key}\`];
}
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT} with ${sorted.length} entries`);
const byCat = {};
for (const [k] of sorted) {
  const c = k.split(":")[0];
  byCat[c] = (byCat[c] ?? 0) + 1;
}
console.log(byCat);
